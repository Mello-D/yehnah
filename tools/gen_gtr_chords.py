"""(chord-harp fork) HARP's guitar sets: tools/gtr/styles.json and chords.json (stoogs/guitchordi, GPL-3.0-only: 50 chord
styles of 11 chords, and the six-string standard-tuning voicing of each of its 294 chords) into firmware/src/harp_gtr.h.
  GT_GEN[set]        the style's family (0 .. GT_NGEN - 1, GT_GNAME)
  GT_CH[set][key]    the chord: root pitch class * 21 + quality (GT_QSUF), key 0..10 (key 11 plays chord 1 again)
  GT_NOTES[chord]    its six strings, low to high, MIDI notes (0: muted) in the style's own key (C when ROOT is C)
Usage: python3 tools/gen_gtr_chords.py   (writes firmware/src/harp_gtr.h)"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'firmware', 'src', 'harp_gtr.h')
chords = json.load(open(os.path.join(ROOT, 'tools', 'gtr', 'chords.json')))
styles = json.load(open(os.path.join(ROOT, 'tools', 'gtr', 'styles.json')))['styles']
PC = {'C': 0, 'C#': 1, 'Db': 1, 'D': 2, 'Eb': 3, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'Gb': 6, 'G': 7, 'Ab': 8, 'G#': 8,
      'A': 9, 'Bb': 10, 'A#': 10, 'B': 11}
QUAL = ['major', 'm', '7', 'maj7', 'm7', '6', 'm6', 'sus2', 'sus4', 'add9', '5', '9', 'm9', 'maj9', '13', 'dim7', 'm7b5',
        '7sus4', '7#9', '7b9', 'aug']
assert len(QUAL) == 21
meta = chords['voicingMetadata']
notes = [None] * (12 * 21)
for name, m in meta.items():
    i = PC[m['root']] * 21 + QUAL.index(m['quality'])
    v = [0 if n is None else n for n in chords['voicings'][name]]
    assert notes[i] is None or notes[i] == v, name
    notes[i] = v
assert all(notes), 'a chord without voicing'
FAM = []
for s in styles:
    if s['family'] not in FAM:
        FAM.append(s['family'])
GN = {'Original': 'GT ORIG', 'Jazz': 'GT JAZZ', 'Lo-fi': 'GT LOFI', 'Rock': 'GT ROCK', 'Blues': 'GT BLUES',
      'Pop': 'GT POP', 'Soul': 'GT SOUL', 'Folk': 'GT FOLK', 'Ambient': 'GT AMB'}
order = [s['family'] for s in styles]
assert order == sorted(order, key=FAM.index), 'families must be contiguous'
ch = []
for s in styles:
    row = []
    for c in s['slots']:
        m = meta[c]
        row.append(PC[m['root']] * 21 + QUAL.index(m['quality']))
    assert len(row) == 11
    ch.append(row)
o = ['/* SPDX-License-Identifier: GPL-3.0-only */',
     '/* generated by tools/gen_gtr_chords.py from tools/gtr/ (styles.json, chords.json) (stoogs/guitchordi, GPL-3.0-only): its 50 chord styles',
     ' * and their standard-tuning six-string voicings (harp.c gt_*). Do not edit */',
     '#define GT_NSET %du' % len(styles), '#define GT_NGEN %du' % len(FAM),
     'static const char *const GT_GNAME[GT_NGEN + 1] = {%s, 0};' % ', '.join('"%s"' % GN[f] for f in FAM),
     'static const uint8_t GT_GEN[GT_NSET] = {%s};' % ', '.join(str(FAM.index(s['family'])) for s in styles),
     'static const char *const GT_QSUF[21] = {%s};' % ', '.join('"%s"' % ('' if q == 'major' else q) for q in QUAL),
     'static const uint16_t GT_CH[GT_NSET][11] = {']
for r in ch:
    o.append('    {%s},' % ', '.join(str(x) for x in r))
o.append('};')
o.append('static const uint8_t GT_NOTES[252][6] = {')
for i in range(0, 252, 2):
    o.append('    ' + ' '.join('{%s},' % ', '.join(str(x) for x in notes[j]) for j in (i, i + 1)))
o.append('};')
open(OUT, 'w').write('\n'.join(o) + '\n')
print('wrote', OUT, len(styles), 'styles', len(FAM), 'families')
