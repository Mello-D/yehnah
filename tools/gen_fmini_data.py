#!/usr/bin/env python3
"""Generates firmware/src/eng_fmini_data.h and eng_fmini_filter.h from FMini-1's sources (ruppert/fmini-1, GPL-3.0):
the 200 factory patches (FMINI_FACTORY), their presets (FMINI_PRESETS, the pattern hint dropped), the per-patch LFO / level /
modulation (FMINI_X, the arpeggiator, FX and octave dropped) and the ladder's tables (the FILT page's graphs dropped).
usage: gen_fmini_data.py <fmini-1 checkout> <out dir>"""
import re, sys
src, out = sys.argv[1] + "/firmware/src/", sys.argv[2] + "/"
pre = open(src + "eng_fmini_presets.h").read().split("\n")
def block(start_pat):
    i = next(k for k, l in enumerate(pre) if start_pat in l)
    j = next(k for k in range(i, len(pre)) if pre[k].startswith("};"))
    return pre[i:j + 1]
fac = block("FMINI_FACTORY[")
cats = next(l for l in pre if l.startswith("#define FMINI_CATS"))
cats = re.sub(r'"([A-Z]+)"', lambda m: '"' + m.group(1).replace("F", "X") + '"', cats.split("/*")[0]).rstrip()
prs = [re.sub(r", PAT\(\d+\)", "", l) for l in block("FMINI_PRESETS[")]
xs = block("FMINI_X[")
xo = [xs[0].replace("fmini_x_t", "fmini_x_t")]
for l in xs[1:-1]:
    m = re.match(r"\s*\{\{[^}]*\}, \{(\d+), (\d+), (\d+), \d+\}, \{[^}]*\}, (\d+), \{(-?\d+), (-?\d+), (-?\d+)\}, -?\d+\},(.*)", l)
    xo.append("    {{%s, %s, %s}, %s, {%s, %s, %s}},%s" % (*m.groups()[:3], m.group(4), *m.groups()[4:7], m.group(8)))
xo.append("};")
h = open(out + "eng_fmini_data.h", "w")
h.write("/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/gen_fmini_data.py from FMini-1's eng_fmini_presets.h (ruppert/fmini-1, GPL-3.0): the 200 factory patches. Do not edit. */\n\n")
h.write("\n".join(fac) + "\n" + cats + "\n")
h.write("/* {CUT, EMPH, CNTR, F.ATK, F.DEC, F.SUS, MOD, (E7: set from the patch)}, {ATK DEC SUS REL}, MONO, the sends */\n")
h.write("\n".join(prs) + "\n")
h.write("/* per patch: the LFO {RATE WAVE FADE}, the LEVEL, the modulation {LFO>PITCH LFO>AMP CONTOUR>PITCH} */\n")
h.write("typedef struct { uint8_t lfo[3], level; int8_t mod[3]; } fmini_x_t;\nstatic const fmini_x_t FMINI_X[FMINI_NFACTORY] = {\n")
h.write("\n".join(xo[1:]) + "\n")
h.close()
f = open(src + "eng_fmini_filter.h").read()
f = re.sub(r"static const int16_t FMINI_GRAPH(_HP)?\[17\]\[73\].*?\n\};\n\n?", "", f, flags=re.S)
open(out + "eng_fmini_filter.h", "w").write(f.replace("Generated by tools/fmini_filter.py (do not edit by hand)", "Generated by FMini-1's tools/fmini_filter.py (ruppert/fmini-1, GPL-3.0; the FILT page's graphs dropped)"))
