"""(chord-harp fork) HARP's J-6 sets: tools/j6/chordsets.json (benbadio/hera-fm1 76b7ee8 data/chordsets.json,
GPL-3.0-only: the Roland J-6's 100 chord sets, 12 chords each, as its manual voices them) into
firmware/src/harp_j6.h. The sets are ordered by genre (J6_GNAME, the J-6 order within one), each chord packed:

  J6_CH[set][key]  type (9 bits) | the bass's place - (C3 + key) + 24 (6 bits) << 9
  J6_TY[type]      the notes over the bass (6 bits each, 0 none) | suffix << 18 (7 bits) | the root over the bass
                   (pitch class) << 25 | slash << 29 (the name ends "/" and the bass's)
  J6_SUF           the names' suffixes, 0-separated ("m7", "M9/#11", ...)

Usage: python3 tools/gen_j6_chords.py   (writes firmware/src/harp_j6.h)"""
import json
import os
import re
G = "   /* (chord-harp fork: the resource region, res.c) */"

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'j6', 'chordsets.json')
OUT = os.path.join(ROOT, 'firmware', 'src', 'harp_j6.h')

GENRES = [  # (the knob's name, up to 7 letters; the J-6 genres it takes)
    ('POP', ['Pop', 'Pop Min', 'Pop/Synth']),
    ('JAZZ', ['Jazz', 'Jazz Min']),
    ('BOSSA', ['Jazz/Bossa', 'Bossa Nova']),
    ('BLUES', ['Blues']),
    ('FUNK', ['Funk']),
    ('R&B', ['Gospel/R&B', 'Lofi R&B']),
    ('NEOSOUL', ['Neo Soul', 'Neo-Soul']),
    ('TRAD', ['Trad Maj', 'Trad Min', 'Trad Min 2']),
    ('CLASSIC', ['Classical']),
    ('CINEMA', ['Cinematic', 'Cinematic/Synthwave', 'Cinematic/House', 'New Age/Cinematic']),
    ('SYNTH', ['Synthwave', 'Synthwave/House']),
    ('HOUSE', ['House', 'Jazz House', 'House/Techno', 'Techno']),
    ('EDM', ['EDM', 'Trance']),
    ('MODERN', ['Modern']),
    ('STACKS', ['Oct Stack', '4th Stack', '5th Stack']),
    ('UTILITY', ['Utility']),
]
STACK = {'Oct Stack': 'oct', '4th Stack': '4th', '5th Stack': '5'}   # (their chords have no names)
SUFFIX = {  # one spelling for each
    'maj7': 'M7', 'maj9': 'M9', 'Maj13': 'M13', ' dim7': 'dim7', 'Dim': 'dim', 'DimM7': 'dimM7', 'M': '',
    'mAdd9': 'madd9', 'M13(no 3)': 'M13(no3)', 'M9(no 3)': 'M9(no3)', 'M9 (no3)': 'M9(no3)', 'm7 add 13': 'm7add13',
    'maj7/9': 'M7/9', 'FM7': 'M7', 'M add2': 'add2', 'M add4': 'add4', 'm6 add b13': 'm6addb13',
}
PC = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}


def pc(s):
    return (PC[s[0]] + s.count('#') - s.count('b')) % 12


def main():
    sets = json.load(open(SRC))
    gidx = {g: i for i, (_, gs) in enumerate(GENRES) for g in gs}
    sets.sort(key=lambda s: (gidx[s['genre']], s['set']))
    sufs, types, ch = [], [], []
    for s in sets:
        row = []
        for c in sorted(s['chords'], key=lambda c: c['key']):
            nt = sorted(set(c['notes']))   # (set 43's A#/F has its F twice)
            lo = nt[0]
            if s['genre'] in STACK:
                rt, sx, sl = lo % 12, STACK[s['genre']], 0
            else:
                m = re.match(r'^([A-G][#b]?)(.*?)(?:/([A-G][#b]?))?$', c['name'].replace('#FM7', '#M7'))
                rt, sx, sl = pc(m.group(1)), m.group(2), int(m.group(3) is not None)
                sx = SUFFIX.get(sx, sx)
                sl &= (rt - lo) % 12 != 0   # (named by its lowest note: 7 chords name another bass; C/G on C is C)
            if sx not in sufs:
                sufs.append(sx)
            iv = [n - lo for n in nt[1:]] + [0] * (4 - len(nt))
            assert all(0 < x < 64 for x in iv[:len(nt) - 1]) and len(nt) <= 4
            ty = iv[0] | iv[1] << 6 | iv[2] << 12 | sufs.index(sx) << 18 | ((rt - lo) % 12) << 25 | sl << 29
            if ty not in types:
                types.append(ty)
            off = lo - (48 + c['key']) + 24
            assert 0 <= off < 64
            row.append(types.index(ty) | off << 9)
        ch.append(row)
    assert len(types) < 512 and len(sufs) < 128 and len(ch) == 100
    gen = [gidx[s['genre']] for s in sets]
    out = ['/* SPDX-License-Identifier: GPL-3.0-only */',
           '/* generated by tools/gen_j6_chords.py from tools/j6/chordsets.json (benbadio/hera-fm1, GPL-3.0-only): the',
           ' * Roland J-6\'s 100 chord sets, ordered by genre (harp.c j6_*). Do not edit */',
           '#define J6_NSET %du' % len(ch), '#define J6_NGEN %du' % len(GENRES),
           'static const char *const J6_GNAME[J6_NGEN + 2] = {"HARP", %s, 0};   /* (0: HARP\'s own MAJ1..MIN8) */'
           % ', '.join('"%s"' % g for g, _ in GENRES),
           'static const uint8_t J6_GEN[J6_NSET] = {%s};   /* (each set\'s genre, J6_GNAME) */' % ', '.join(str(g + 1) for g in gen),
           'static const char J6_SUF[] YEHNAH_RES = "%s";' % '\\000'.join(sufs),
           'static const uint32_t J6_TY[%d] YEHNAH_RES = {%s' % (len(types), G)]
    for i in range(0, len(types), 8):
        out.append('    ' + ' '.join('%du,' % t for t in types[i:i + 8]))
    out.append('};')
    out.append('static const uint16_t J6_CH[J6_NSET][12] YEHNAH_RES = {' + G)
    for row in ch:
        out.append('    {' + ', '.join(str(x) for x in row) + '},')
    out.append('};')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('%s: %d types, %d suffixes, ~%d bytes' % (OUT, len(types), len(sufs),
                                                   len(types) * 4 + len(ch) * 24 + len(gen) + sum(len(x) + 1 for x in sufs)))


if __name__ == '__main__':
    main()
