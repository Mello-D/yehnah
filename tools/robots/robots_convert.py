"""(chord-harp fork, 2026-10-28) The engine robots' parts (export_parts.mjs's PNGs, or the same PNGs edited by hand) as
palette-indexed, run-length-coded tables for the firmware: firmware/src/ui_robots.h (ui_robot.c draws them).
    python3 tools/robots/robots_convert.py [PARTSDIR] [OUT]     (defaults tools/robots/parts, firmware/src/ui_robots.h)
The palette RB_PAL: 0 nothing, 1..5 the head's ramp, 6..10 the body's, 11..15 the accent's (a robot's own, set when it is
drawn: RB_PAL's 0 there), then the page's ramps (RB_<RAMP> + 0..4, dark to light), then every other colour its code
draws (RB_C_<rrggbb>). A part's pixels: its marker-ramp grays (MARK) are 1..5 (the head's or body's ramp, by the part),
any other colour must be in the palette (else this stops, naming the pixel). Coded row by row as one stream: a byte
under 0xF0 one pixel, 0xF0 + n a run of n + 2 of the next byte."""
import json, os, sys
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
pdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, 'parts')
outp = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', '..', 'firmware', 'src', 'ui_robots.h')
d = json.load(open(os.path.join(pdir, 'robots.json')))
pal, first = [None] * 16, {}
for name, ramp in d['ramps']:
    for c in ramp:
        first.setdefault(c, len(pal))
        pal.append(c)
for c in d['misc']:
    first[c] = len(pal)
    pal.append(c)
assert len(pal) < 0xF0
mark = {c: i + 1 for i, c in enumerate(d['mark'])}
def rgb565(c):
    r, g, b = int(c[1:3], 16), int(c[3:5], 16), int(c[5:7], 16)
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3

parts, data = [], []
for line in open(os.path.join(pdir, 'parts.tsv')):
    if not line.strip():
        continue
    name, x, y = line.split('\t')
    im = Image.open(os.path.join(pdir, name + '.png')).convert('RGBA')
    w, h = im.size
    px = []
    for j in range(h):
        for i in range(w):
            r, g, b, a = im.getpixel((i, j))
            c = '#%02x%02x%02x' % (r, g, b)
            if a < 128:
                px.append(0)
            elif c in mark:
                px.append(mark[c])
            elif c in first:
                px.append(first[c])
            else:
                sys.exit(f'{name}.png pixel {i},{j}: {c} is not a robot colour (robots.json: ramps, misc, mark)')
    off, k = len(data), 0
    while k < len(px):
        n = 1
        while k + n < len(px) and px[k + n] == px[k] and n < 17:
            n += 1
        if n >= 2:
            data += [0xF0 + n - 2, px[k]]
        else:
            data.append(px[k])
        k += n
    parts.append((name, int(x), int(y), w, h, off))

def ident(s):
    return s.upper().replace('-', '_')
o = ['/* SPDX-License-Identifier: GPL-3.0-only', ' * Copyright (C) 2026 Mello-D */',
     '/* GENERATED by tools/robots/robots_convert.py from tools/robots/parts (export_parts.mjs: engine_robots.html). Do not edit:',
     ' * edit the page or the PNGs and convert again. The robots\' palette, their parts (run-length coded), the robots. */',
     '#define RB_ROLE_H 0u  /* a part\'s marker ramp: the head\'s colours (1..5), the body\'s (6..10), the accent (11..15) */',
     '#define RB_ROLE_B 5u', '#define RB_ROLE_A 10u']
base = 16
for name, ramp in d['ramps']:
    o.append(f'#define RB_{ident(name)} {base}u')
    base += 5
for c in sorted(first, key=lambda c: first[c]):
    o.append(f'#define RB_C_{c[1:]} {first[c]}u')
o.append(f'#define RB_INK RB_C_{d["ink"][1:]}')
o.append(f'#define RB_NPAL {len(pal)}u')
o.append('static const uint16_t RB_PAL[RB_NPAL] = {')
o += ['    ' + ', '.join('0x%04X' % (0 if c is None else rgb565(c)) for c in pal[i:i + 12]) + ',' for i in range(0, len(pal), 12)]
o.append('};')
o.append('enum {')
o += [f'    RBP_{ident(p[0])},' for p in parts]
o.append('    RBP_N')
o.append('};')
o.append('typedef struct { int8_t x, y; uint8_t w, h; uint16_t off; } rb_part_t;   /* its top left on the robot\'s grid, size, data */')
o.append('static const rb_part_t RB_PART[RBP_N] = {')
o += [f'    {{{x}, {y}, {w}, {h}, {off}}},   /* {n} */' for n, x, y, w, h, off in parts]
o.append('};')
o.append(f'static const uint8_t RB_DATA[{len(data)}] YEHNAH_RES = {{   /* (chord-harp fork: the resource region, res.c) */')
o += ['    ' + ', '.join(str(v) for v in data[i:i + 24]) + ',' for i in range(0, len(data), 24)]
o.append('};')
kinds = {}
for key in ('head', 'em', 'ant', 'eyes', 'shape'):
    vals = []
    for r in d['robots']:
        if r[key] not in vals:
            vals.append(r[key])
    for first_ in ('none', 'std'):                      # (the plain one 0)
        if first_ in vals:
            vals.remove(first_); vals.insert(0, first_)
    kinds[key] = vals
    o.append('enum { ' + ', '.join(f'RB_{key.upper()}_{ident(v)}' for v in vals) + ' };')
o.append('typedef struct { uint8_t head, hr, br, ac, em, ant, eyes, talk, shape; } rb_robot_t;   /* hr br ac: RB_<RAMP> */')
o.append(f'#define RB_NROBOTS {len(d["robots"])}u')
o.append('static const rb_robot_t RB_ROBOTS[RB_NROBOTS] = {')
for r in d['robots']:
    f = [f'RB_HEAD_{ident(r["head"])}', f'RB_{ident(r["hr"])}', f'RB_{ident(r["br"])}', f'RB_{ident(r["ac"])}',
         f'RB_EM_{ident(r["em"])}', f'RB_ANT_{ident(r["ant"])}', f'RB_EYES_{ident(r["eyes"])}', '1' if r['talk'] else '0',
         f'RB_SHAPE_{ident(r["shape"])}']
    o.append(f'    {{{", ".join(f)}}},   /* {r["name"]} */')
o.append('};')
o.append('static const uint8_t RB_HEAD_TOP[] = {' + ', '.join(str(d['head_top'][k]) for k in kinds['head']) + '};   /* the antenna\'s foot */')
o.append('enum { ' + ', '.join(f'RB_{ident(r["name"])}' for r in d['robots']) + ' };')
# the moves: each arm's state (RB_ARM_DOWN .. RB_ARM_DIAG: the arm parts' order after DOWN0..3), lean, squat, a foot up,
# nod, a side step
arms = ['down', 'up', 'out', 'wave', 'hips', 'diag']
o.append('enum { RB_ARM_DOWN, RB_ARM_UP = 4, RB_ARM_OUT, RB_ARM_WAVE, RB_ARM_HIPS, RB_ARM_DIAG };')
o.append('typedef struct { uint8_t la, ra; int8_t lean, squat, lift, nod, shift; } rb_pose_t;')
o.append(f'#define RB_NPOSES {len(d["poses"])}u')
o.append('static const rb_pose_t RB_POSE[RB_NPOSES] = {')
arm_id = lambda a: 'RB_ARM_' + a.upper()
o += ['    {' + ', '.join([arm_id(p['la']), arm_id(p['ra'])] + [str(p.get(k, 0)) for k in ('lean', 'squat', 'lift', 'nod', 'shift')]) + '},'
      for p in d['poses']]
o.append('};')
# HOME's stars (the page's, on a sky 22 art pixels high): x, y, size 1..3
import math
fr = lambda v: v - math.floor(v)
st = [(int(fr(math.sin(i * 127.1) * 43758.5) * 120), int(fr(math.sin(i * 311.7) * 24634.6) * 22), 1 + i % 3) for i in range(70)]
o.append(f'#define RB_NSTARS {len(st)}u')
o.append('static const uint8_t RB_STARS[RB_NSTARS][3] = {')
o += ['    ' + ' '.join('{%d, %d, %d},' % t for t in st[i:i + 10]) for i in range(0, len(st), 10)]
o.append('};')
open(outp, 'w').write('\n'.join(o) + '\n')
print(f'robots_convert: {len(parts)} parts, {len(data)} B of data, {len(pal)} colours -> {outp}')
