"""(chord-harp fork, 2026-10-30) WSEQ's band-limited waves (firmware/src/eng_wseq.c wseq_wave), written to
firmware/src/wseq_waves.h (committed: no build step). Usage: python3 tools/gen_wseq_waves.py [out.h]

Clipper's WSEQ plays FMX's tables (fmx_tables.h, 13 x 1024 int16: 26 KB, FMX not built here). These are the ones
that a formula does not give as they are: SAW, SQR and PULSE (25 %) to the 48th harmonic and their copies to the 8th
(the high notes), each harmonic tapered by a raised cosine, peak 32767: gen_fmx.py's, at 256 points (3 KB; read
with linear interpolation, the 48th harmonic still 5 points a period). TRI HALF ABS QUART SIN8 are computed in
wseq_wave, the same shapes."""
import math
import sys

N = 256
TAU = 2 * math.pi


def additive(amps):
    v = [sum(a * math.sin(TAU * k * i / N + ph) for k, a, ph in amps) for i in range(N)]
    pk = max(abs(x) for x in v)
    return [int(round(32767 * x / pk)) for x in v]


def taper(k, nh):
    return 0.5 + 0.5 * math.cos(math.pi * k / (nh + 1))


def saw(nh):
    return additive([(k, 1.0 / k * taper(k, nh), 0) for k in range(1, nh + 1)])


def sqr(nh):
    return additive([(k, 1.0 / k * taper(k, nh), 0) for k in range(1, nh + 1, 2)])


def pulse(nh, w=0.25):
    return additive([(k, math.sin(math.pi * k * w) / k * taper(k, nh), -math.pi / 2) for k in range(1, nh + 1)])


WAVES = [("SAW", saw(48)), ("SQR", sqr(48)), ("PULSE", pulse(48)), ("SAW8", saw(8)), ("SQR8", sqr(8)),
         ("PULS8", pulse(8))]


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "firmware/src/wseq_waves.h"
    with open(out, "w") as f:
        f.write("/* generated by tools/gen_wseq_waves.py (Clipper's tools/gen_fmx.py waves, GPL-3.0-only): WSEQ's SAW SQR PULSE\n"
                " * to the 48th harmonic, then to the 8th (the high notes); %d points, peak 32767 */\n" % N)
        f.write("#pragma once\n#define WSEQ_TN %du\n" % N)
        f.write("enum { WT_SAW, WT_SQR, WT_PULSE, WT_SAW8, WT_SQR8, WT_PULS8, WT_N };\n")
        f.write("static const int16_t WSEQ_WAVE[WT_N][WSEQ_TN] YEHNAH_RES = {   /* (chord-harp fork: the resource region, res.c) */\n")
        for name, v in WAVES:
            f.write("    {   /* %s */\n" % name)
            for i in range(0, N, 16):
                f.write("        " + ", ".join(str(x) for x in v[i:i + 16]) + ",\n")
            f.write("    },\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
