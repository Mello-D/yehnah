"""(0.9.7, flash) The drum bars of firmware/src/song_dice.c (DRUM_BAR, DRUM_BAR_KICK: '.' 'x' a hit, 'a' accented, 'g' a
ghost; text there, read here, not compiled) packed: each distinct lane once at 2 bits a step (DB_LANE: step 4i in the top
bits of byte i, '.' 0 'x' 1 'a' 2 'g' 3), the table as lane numbers (DRUM_BAR_I; song_dice.c db_char).
(2026-11-10: GEN's own drum maps and bass archetypes went with GEN, gen.c / gen_tables.c.)
  gen_drum_maps.py SONG_DICE.c DICE_OUT.h"""
import re
import sys
from pathlib import Path


def main(dice, dout):
    d = Path(dice).read_text()
    m = re.search(r"static const char \*const DRUM_BAR\[\]\[8\] = \{(.*?)\n\};", d, re.S)
    brows = re.findall(r"\[(DS_\w+)\]\s*=\s*\{([^}]*)\}", m.group(1))
    kick = re.findall(r'"([^"]*)"', re.search(r"static const char \*const DRUM_BAR_KICK\[1\] = \{(.*?)\};", d, re.S).group(1))
    bl, bi = [""], {"": 0}
    code = {".": 0, "x": 1, "a": 2, "g": 3}

    def blane(x):
        if x not in bi:
            assert len(x) == 16 and set(x) <= set(code), f"gen_drum_maps: bar lane {x!r}"
            assert set(x) != {"."}, "an all-rest lane would read as none"
            bi[x] = len(bl)
            bl.append(x)
        return bi[x]
    btab = []
    for name, body in brows:
        ls = re.findall(r'"([^"]*)"', body)
        assert len(ls) == 8, f"gen_drum_maps: {name} has {len(ls)} lanes"
        btab.append((name, [blane(x) for x in ls]))
    kk = [blane(x) for x in kick]
    L = ["/* generated by tools/gen_drum_maps.py from firmware/src/song_dice.c (DRUM_BAR, DRUM_BAR_KICK, as text there): */",
         "/* each lane once, 2 bits a step ('.' 0 'x' 1 'a' 2 'g' 3; lane 0: none); the table as lane numbers */",
         "#pragma once", "#include <stdint.h>"]
    L.append(f"static const uint8_t DB_LANE[{len(bl)}][4] = {{")
    for x in bl:
        v = [code[c] for c in x] if x else [0] * 16
        L.append("    {" + ", ".join(f"0x{v[4 * i] << 6 | v[4 * i + 1] << 4 | v[4 * i + 2] << 2 | v[4 * i + 3]:02X}" for i in range(4))
                 + "}," + (f"   /* {x} */" if x else "   /* (none) */"))
    L.append("};")
    L.append("static const uint8_t DRUM_BAR_I[][8] = {")
    for name, v in btab:
        L.append(f"    [{name}] = {{{', '.join(map(str, v))}}},")
    L.append("};")
    L.append(f"#define DRUM_BAR_KICK_I {kk[0]}u")
    Path(dout).write_text("\n".join(L) + "\n")
    print(f"DICE's drum bars: {len(btab)}, {len(bl) - 1} distinct lanes, {4 * len(bl) + 8 * len(btab)} B -> {dout}")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:3]))
