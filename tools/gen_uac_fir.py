"""The polyphase FIR of the USB audio input's 44.1 -> 48 kHz resampler (src/usb.c, YEHNAH_UAC_48K).

48000 / 44100 = 160 / 147: up by L = 160, low-pass, down by M = 147. Output frame k sits at input time
k * 147 / 160: phase p = (k * 147) % 160, newest input frame floor(k * 147 / 160). Each phase is N taps of
the prototype (a Kaiser-windowed sinc of 160 * N taps at 7.056 MHz, cut-off FC):
    y[k] = sum_j  PROTO[p + 160 j] * x[base - j],   j = 0 .. N-1
The table holds the taps oldest input first (UAC_TAB[p][i] = L * PROTO[p + 160 (N-1-i)]), Q15, and only the
phases 0 .. 79: the prototype is symmetric, so phase 159 - p is phase p read backwards (usb.c does that). Each
phase's taps sum to exactly 1 << 15 (unity gain at DC, the rounding left on its largest tap).
(2026-11-18) N = 12, FC = 20 kHz, beta 7.5, Q15 (was 24 taps, 22 kHz, beta 9, Q30 and all 160 phases in the flash:
15,360 B, now 1,920 B). The design is SLOOP 2.5's (github.com/isod89/sloop-fm1, GPL-3.0, after Felucca 1.1.5's
generator by Leo Kuroshita): images that would fold into the audible band about 80 dB down, the passband flat to
about 12 kHz (-1 dB at 16 kHz, -2.7 dB at 18 kHz, -5.9 dB at 20 kHz), the 1 kHz SNR above 80 dB. For recording
into a phone or a sampler; tests/uac_test.c measures it on the C code.
  tools/gen_uac_fir.py [OUT]   (default firmware/src/uac_fir.h); numpy only."""
import sys
from pathlib import Path

import numpy as np

L, M, N = 160, 147, 12
FC, BETA, QB = 20000.0, 7.5, 15
FS = 44100.0


def prototype():
    n = L * N
    t = np.arange(n) - (n - 1) / 2.0
    fc = FC / (FS * L)                                   # cycles per sample at the up-sampled rate
    h = 2 * fc * np.sinc(2 * fc * t) * np.kaiser(n, BETA)
    return h / h.sum() * L                               # DC gain L: unity after the zero stuffing


def table():
    h = prototype()
    tab = np.zeros((L, N), dtype=np.int64)
    for p in range(L):
        c = h[p::L][::-1]                                # oldest input first
        q = np.round(c * (1 << QB)).astype(np.int64)
        q[np.argmax(np.abs(c))] += (1 << QB) - q.sum()
        tab[p] = q
    for p in range(L // 2):                              # the symmetry the C code relies on
        assert (tab[L - 1 - p] == tab[p][::-1]).all() or np.abs(tab[L - 1 - p] - tab[p][::-1]).max() <= 1
    return tab


def main():
    out = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "firmware" / "src" / "uac_fir.h")
    tab = table()
    h = L // 2
    chk = sum((p * N + j + 1) * int(tab[p][j]) for p in range(h) for j in range(N)) % (1 << 64)
    habs = max(int(np.abs(tab[p]).sum()) for p in range(h))
    assert habs * 32768 < (1 << 31)                      # usb.c sums in 32 bits
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Copyright (C) 2026 Leo Kuroshita (@kurogedelic), Hügelton Instruments */",
        "/* generated by tools/gen_uac_fir.py: do not edit. The 44.1 -> 48 kHz polyphase FIR of the USB",
        f" * audio input (usb.c): L {L}, M {M}, {N} taps per phase, Kaiser beta {BETA:g}, cut-off {FC:g} Hz, Q{QB};",
        f" * phases 0..{h - 1} only (phase {L - 1} - p = phase p backwards: usb.c reads it so), taps oldest input first.",
        " * (2026-11-18) the design of SLOOP 2.5 (isod89/sloop-fm1, GPL-3.0): 1,920 B, was 15,360 B (24 taps, Q30, 160 phases). */",
        f"#define UAC_FIR_L {L}u",
        f"#define UAC_FIR_M {M}u",
        f"#define UAC_FIR_N {N}u",
        f"#define UAC_FIR_Q {QB}",
        f"#define UAC_FIR_H {h}u                       /* phases stored */",
        f"#define UAC_FIR_ABS {habs}                    /* the largest sum of |tap| in a phase: x 32768 stays under 2^31 */",
        f"#define UAC_FIR_CHK 0x{chk:016X}ull   /* sum of (p * N + j + 1) * tap[p][j], phases 0..{h - 1}, mod 2^64 */",
        f"static const int16_t UAC_TAB[{h}][{N}] = {{",
    ]
    for p in range(h):
        lines.append("    {" + ", ".join(str(int(v)) for v in tab[p]) + "},")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {h} x {N} taps, {h * N * 2} B")


if __name__ == "__main__":
    main()
