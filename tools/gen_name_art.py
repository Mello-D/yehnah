"""(chord-harp fork) The boot screen's name, "Yehnah", in an 80s arcade pixel font: Press Start 2P (SIL OFL 1.1,
assets/fonts/pressstart2p), an 8 x 8 grid per letter, read once into one bit a pixel (was "VitaminDSDC" in Caveat, a
4-bit coverage picture, 2.9 KB).

  gen_name_art.py OUT.h

Out: NAME_N letters, NAME_G (8 bytes a letter, a row a byte, the left pixel in bit 7). ui_draw.c draw_splash scales
them up. Needs PIL (run by hand: the header is committed, firmware/src/ui_name_art.h).
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets" / "fonts" / "pressstart2p" / "PressStart2P-Regular.ttf"
NAME = "Yehnah"


def main():
    out = Path(sys.argv[1])
    font = ImageFont.truetype(str(FONT), 8)              # (its own size: one font pixel a pixel)
    data = []
    for ch in NAME:
        img = Image.new("L", (8, 8), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        px = img.load()
        data += [sum(128 >> x for x in range(8) if px[x, y] >= 128) for y in range(8)]
    lines = [f"/* generated by tools/gen_name_art.py from Press Start 2P (SIL OFL 1.1, assets/fonts/pressstart2p): \"{NAME}\",",
             " * 8 x 8 a letter, a row a byte (the left pixel in bit 7). Do not edit. */",
             f"#define NAME_N {len(NAME)}",
             f"static const uint8_t NAME_G[{len(data)}] = {{"]
    for i in range(0, len(data), 8):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in data[i:i + 8]) + ",   /* " + NAME[i // 8] + " */")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"name art: {len(NAME)} letters, {len(data)} B -> {out}")
    for y in range(8):                                   # (a look in the terminal)
        print("".join("#" if data[i * 8 + y] & (128 >> x) else "." for i in range(len(NAME)) for x in range(8)))


if __name__ == "__main__":
    main()
